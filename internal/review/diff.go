package review

import (
	"fmt"
	"regexp"
	"strconv"
	"strings"
	"unicode/utf8"

	"github.com/Pense-Laranja/aspect/internal/speccontext"
)

// Fitting a git diff to a model's prompt budget without losing reviewable
// code takes two steps, both lossless for review purposes:
//
//  1. Files no reviewer reads line by line (vendored, minified, lock files,
//     binaries, generated code) are replaced by a one-line stub naming the
//     file and its size, so reviewers still see that it changed. In one real
//     PR, 1.7 MB of a 2.2 MB diff was a minified vendored pdf.js.
//  2. What remains is split into parts that each fit the budget, cut at file
//     boundaries, then at hunk boundaries for a file too big on its own.
//     Every part carries the full list of changed files, so a reviewer of
//     one part knows what else the change touches.
//
// A prompt over the model's input limit is refused or cut, so every part is
// built to fit. Sizes are counted in bytes, which errs toward smaller parts
// for text that is not ASCII.

// charsPerToken: code and diffs average 3.5-4 characters per token; 3 errs
// toward smaller parts. It is speccontext's, so CODE_REVIEWER_SPEC_BUDGET
// counts tokens as the prompt budget does.
const charsPerToken = float64(speccontext.CharsPerToken)

// minifiedAvgLine: a text file whose added lines average this long is
// minified even when its name does not say so (pdf.worker.mjs).
const minifiedAvgLine = 400

var (
	lockFiles = map[string]bool{
		"go.sum": true, "package-lock.json": true, "npm-shrinkwrap.json": true, "yarn.lock": true,
		"pnpm-lock.yaml": true, "Cargo.lock": true, "poetry.lock": true, "Pipfile.lock": true,
		"uv.lock": true, "composer.lock": true, "Gemfile.lock": true, "bun.lockb": true, "flake.lock": true,
	}
	vendorDirRE  = regexp.MustCompile(`(^|/)(vendor|node_modules|third_party|bower_components)/`)
	minifiedRE   = regexp.MustCompile(`\.min\.(js|mjs|cjs|css)$|\.(js|mjs|css)\.map$|\.map$`)
	generatedRE  = regexp.MustCompile(`Code generated .* DO NOT EDIT|@generated\b|<auto-generated`)
	diffGitRE    = regexp.MustCompile(`^diff --git a/(.*?) b/(.*)$`)
	hunkHeaderRE = regexp.MustCompile(`^@@ -\d+(?:,\d+)? \+(\d+)(?:,\d+)? @@`)
)

// estimateTokens is a conservative token count for text.
func estimateTokens(text string) int {
	return int((float64(len(text)) + charsPerToken - 1) / charsPerToken)
}

// fileDiff is one file's section of a unified diff.
type fileDiff struct {
	path    string
	header  string // "diff --git" through the line before the first @@
	hunks   []string
	added   int
	removed int
	binary  bool
}

func (f *fileDiff) text() string { return f.header + strings.Join(f.hunks, "") }

type omittedFile struct {
	path           string
	reason         string
	added, removed int
	size           int
}

func (o omittedFile) stub() string {
	return fmt.Sprintf("- %s (+%d/-%d lines, %d KB): %s", o.path, o.added, o.removed, o.size/1024, o.reason)
}

// splitDiff is a diff with the files no one reviews set apart.
type splitDiff struct {
	files   []*fileDiff
	omitted []omittedFile
}

// overview is the changed-file list with sizes, plus the omitted files:
// shared by every part.
func (s *splitDiff) overview() string {
	lines := []string{fmt.Sprintf("Changed files (%d):", len(s.files)+len(s.omitted))}
	for _, f := range s.files {
		lines = append(lines, fmt.Sprintf("- %s (+%d/-%d)", f.path, f.added, f.removed))
	}
	if len(s.omitted) > 0 {
		lines = append(lines, "\nNot shown below (third-party, minified, lock, binary or generated; "+
			"no reviewable source, listed so you know they changed):")
		for _, o := range s.omitted {
			lines = append(lines, o.stub())
		}
	}
	return strings.Join(lines, "\n")
}

// diffPart is one prompt's share of the diff.
type diffPart struct {
	index, total int // index is 1-based
	text         string
	files        []string
}

func (p diffPart) label() string { return fmt.Sprintf("part %d of %d", p.index, p.total) }

// parseDiff splits unified diff text into per-file sections, keeping every
// byte.
func parseDiff(diff string) []*fileDiff {
	var files []*fileDiff
	var cur *fileDiff
	inHunks := false
	for _, line := range strings.SplitAfter(diff, "\n") {
		if line == "" {
			continue
		}
		if strings.HasPrefix(line, "diff --git ") {
			path := strings.TrimSpace(line[len("diff --git "):])
			if m := diffGitRE.FindStringSubmatch(strings.TrimRight(line, "\n")); m != nil {
				path = m[2]
			}
			cur = &fileDiff{path: path, header: line}
			files = append(files, cur)
			inHunks = false
			continue
		}
		if cur == nil { // text before the first file header
			cur = &fileDiff{}
			files = append(files, cur)
		}
		switch {
		case strings.HasPrefix(line, "@@"):
			cur.hunks = append(cur.hunks, line)
			inHunks = true
		case inHunks:
			cur.hunks[len(cur.hunks)-1] += line
			if strings.HasPrefix(line, "+") {
				cur.added++
			} else if strings.HasPrefix(line, "-") {
				cur.removed++
			}
		default:
			cur.header += line
			if strings.HasPrefix(line, "Binary files ") || strings.HasPrefix(line, "GIT binary patch") {
				cur.binary = true
			}
		}
	}
	return files
}

// unreviewableReason says why a file's diff holds nothing a reviewer reads,
// or "" to keep it.
func unreviewableReason(f *fileDiff) string {
	name := f.path[strings.LastIndex(f.path, "/")+1:]
	switch {
	case f.binary:
		return "binary file"
	case lockFiles[name]:
		return "dependency lock file (the manifest beside it shows the dependency change)"
	case vendorDirRE.MatchString(f.path):
		return "vendored third-party code"
	case minifiedRE.MatchString(f.path):
		return "minified or source-map file"
	}
	var added []string
	total := 0
	for _, h := range f.hunks {
		for _, l := range strings.Split(h, "\n") {
			if strings.HasPrefix(l, "+") {
				added = append(added, l)
				total += utf8.RuneCountInString(l)
			}
		}
	}
	if len(added) > 0 && float64(total)/float64(len(added)) > minifiedAvgLine {
		return "minified content (very long lines)"
	}
	if generatedRE.MatchString(strings.Join(added[:min(5, len(added))], "")) {
		return "generated code (marked DO NOT EDIT)"
	}
	return ""
}

func annotateHunk(hunk string) string {
	lines := strings.SplitAfter(hunk, "\n")
	if len(lines) == 0 {
		return hunk
	}
	m := hunkHeaderRE.FindStringSubmatch(strings.TrimRight(lines[0], "\r\n"))
	if m == nil {
		return hunk
	}
	headLine, err := strconv.Atoi(m[1])
	if err != nil {
		return hunk
	}
	var b strings.Builder
	b.Grow(len(hunk) + len(lines)*8)
	b.WriteString(lines[0])
	for _, line := range lines[1:] {
		switch {
		case strings.HasPrefix(line, "+"):
			fmt.Fprintf(&b, "L%d: %s", headLine, line)
			headLine++
		case strings.HasPrefix(line, " "):
			fmt.Fprintf(&b, "L%d: %s", headLine, line)
			headLine++
		case strings.HasPrefix(line, "-"):
			b.WriteString("OLD: ")
			b.WriteString(line)
		default:
			b.WriteString(line)
		}
	}
	return b.String()
}

func splitReviewable(diff string) *splitDiff {
	s := &splitDiff{}
	for _, f := range parseDiff(diff) {
		reason := ""
		if f.path != "" {
			reason = unreviewableReason(f)
		}
		if reason != "" {
			s.omitted = append(s.omitted, omittedFile{f.path, reason, f.added, f.removed, len(f.text())})
		} else {
			for i, h := range f.hunks {
				f.hunks[i] = annotateHunk(h)
			}
			s.files = append(s.files, f)
		}
	}
	return s
}

const (
	continues = "\n[hunk continues in the next part]\n"
	continued = "[continued from the previous part]\n"
)

// pieces is a file's diff as pieces no larger than budget bytes, cut at
// hunks. Each piece repeats the file header so it reads as a valid diff. A
// single hunk larger than the budget is cut at line boundaries, marked as
// such.
func pieces(f *fileDiff, budget int) []string {
	if t := f.text(); len(t) <= budget {
		return []string{t}
	}
	var out []string
	room := max(1, budget-len(f.header)-len(continues)-len(continued))
	cur := ""
	for _, hunk := range f.hunks {
		if len(hunk) > room {
			if cur != "" {
				out = append(out, f.header+cur)
				cur = ""
			}
			buf := ""
			for _, line := range strings.SplitAfter(hunk, "\n") {
				if line == "" {
					continue
				}
				if buf != "" && len(buf)+len(line) > room {
					out = append(out, f.header+buf+continues)
					buf = continued
				}
				buf += line
			}
			cur = buf
			continue
		}
		if cur != "" && len(cur)+len(hunk) > room {
			out = append(out, f.header+cur)
			cur = ""
		}
		cur += hunk
	}
	if cur != "" || len(out) == 0 {
		out = append(out, f.header+cur)
	}
	return out
}

// chunkDiff packs the reviewable files into as few parts as fit
// budgetTokens each. Files stay in diff order (git sorts by path, so a
// package's files stay together) and a file is only cut when it cannot fit
// a part alone.
func chunkDiff(s *splitDiff, budgetTokens int) []diffPart {
	budget := max(1000, int(float64(budgetTokens)*charsPerToken))
	type group struct {
		text  string
		files []string
	}
	var groups []group
	var g group
	for _, f := range s.files {
		for _, piece := range pieces(f, budget) {
			if g.text != "" && len(g.text)+len(piece) > budget {
				groups = append(groups, g)
				g = group{}
			}
			g.text += piece
			if len(g.files) == 0 || g.files[len(g.files)-1] != f.path {
				g.files = append(g.files, f.path)
			}
		}
	}
	if g.text != "" || len(groups) == 0 {
		groups = append(groups, g)
	}
	parts := make([]diffPart, len(groups))
	for i, g := range groups {
		parts[i] = diffPart{index: i + 1, total: len(groups), text: g.text, files: g.files}
	}
	return parts
}
