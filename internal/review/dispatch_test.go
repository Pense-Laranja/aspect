func TestRequestsInFlightAreCapped(t *testing.T) {
	for _, tc := range []struct{ slots, want int }{{2, 2}, {0, 6}} {
		gate := make(chan struct{})
		var mu sync.Mutex
		inFlight, peak := 0, 0
		client := clientFunc(func(ctx context.Context, req llm.Request) (llm.Response, error) {
			mu.Lock()
			inFlight++
			peak = max(peak, inFlight)
			mu.Unlock()
			<-gate
			mu.Lock()
			inFlight--
			mu.Unlock()
			return llm.Response{Text: `{"summary": "ok"}`}, nil
		})
		rv := &reviewer{client: client, engine: "e"}
		if tc.slots > 0 {
			rv.slots = make(chan struct{}, tc.slots)
		}
		var wg sync.WaitGroup
		for i := 0; i < 6; i++ {
			wg.Add(1)
			go func() { defer wg.Done(); rv.ask(context.Background(), "p", nil, nil) }()
		}
		waitFor(t, func() bool { mu.Lock(); defer mu.Unlock(); return inFlight == tc.want })
		close(gate)
		wg.Wait()
		if peak != tc.want {
			t.Errorf("slots %d: peak %d in flight, want %d", tc.slots, peak, tc.want)
		}
	}
}

type clientFunc func(context.Context, llm.Request) (llm.Response, error)

func (f clientFunc) Complete(ctx context.Context, req llm.Request) (llm.Response, error) {
	return f(ctx, req)
}

