func fileDiffText(path string, hunks, linesPerHunk int, line string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "diff --git a/%s b/%s\n--- a/%s\n+++ b/%s\n", path, path, path, path)
	for h := 0; h < hunks; h++ {
		fmt.Fprintf(&b, "@@ -%d,1 +%d,%d @@ func f%d()\n", h*10+1, h*10+1, linesPerHunk, h)
		for i := 0; i < linesPerHunk; i++ {
			fmt.Fprintf(&b, "+%s # %s h%d l%d\n", line, path, h, i)
		}
	}
	return b.String()
}

func manyFiles() string {
	var b strings.Builder
	for i := 0; i < 10; i++ {
		b.WriteString(fileDiffText(fmt.Sprintf("p/f%d.go", i), 3, 50, "x = 1"))
	}
	return b.String()
}

func TestParsingKeepsEveryByte(t *testing.T) {
	text := fileDiffText("a.go", 2, 3, "x = 1") + fileDiffText("b.go", 1, 3, "x = 1") +
		"diff --git a/c.png b/c.png\nBinary files a/c.png and b/c.png differ"
	var joined strings.Builder
	for _, f := range parseDiff(text) {
		joined.WriteString(f.text())
	}
	if joined.String() != text {
		t.Fatal("parsing lost bytes")
	}
}

func TestSplitReviewableAnnotatesHeadLineNumbers(t *testing.T) {
	diff := strings.Join([]string{
		"diff --git a/pkg/foo.go b/pkg/foo.go",
		"--- a/pkg/foo.go",
		"+++ b/pkg/foo.go",
		"@@ -10,4 +20,5 @@ func foo() {",
		" \tctxLine1()",
		"-\toldCall()",
		"+\tnewCall1()",
		"+\tnewCall2()",
		" \tctxLine2()",
		"@@ -1 +1 @@",
		"-singleOld",
		"+singleNew",
		`\ No newline at end of file`,
		"@@ malformed header @@",
		"+unannotated",
		"",
	}, "\n")

	s := splitReviewable(diff)
	if len(s.files) != 1 {
		t.Fatalf("files = %d, want 1", len(s.files))
	}
	got := s.files[0].text()
	for _, want := range []string{
		"@@ -10,4 +20,5 @@ func foo() {\n",
		"L20:  \tctxLine1()\n",
		"OLD: -\toldCall()\n",
		"L21: +\tnewCall1()\n",
		"L22: +\tnewCall2()\n",
		"L23:  \tctxLine2()\n",
		"@@ -1 +1 @@\n",
		"OLD: -singleOld\n",
		"L1: +singleNew\n",
		"\\ No newline at end of file\n",
		"@@ malformed header @@\n+unannotated\n",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("annotated diff missing %q in:\n%s", want, got)
		}
	}
}

func TestUnreviewableFilesBecomeStubs(t *testing.T) {
	text := fileDiffText("app/main.go", 1, 3, "x = 1") +
		fileDiffText("web/vendor/pdfjs/pdf.js", 1, 3, "x = 1") +
		fileDiffText("web/app.min.js", 1, 3, "x = 1") +
		fileDiffText("go.sum", 1, 3, "x = 1") +
		fileDiffText("gen/api.go", 1, 3, "// Code generated by protoc. DO NOT EDIT.") +
		"diff --git a/web/worker.mjs b/web/worker.mjs\n--- a/x\n+++ b/x\n@@ -0,0 +1 @@\n+" + strings.Repeat("a", 2000) + "\n" +
		"diff --git a/logo.png b/logo.png\nBinary files a/logo.png and b/logo.png differ\n"
	s := splitReviewable(text)
	if len(s.files) != 1 || s.files[0].path != "app/main.go" {
		t.Fatalf("kept %d files", len(s.files))
	}
	got := map[string]bool{}
	for _, o := range s.omitted {
		got[o.path] = true
		if !strings.Contains(s.overview(), o.path) {
			t.Errorf("the overview does not name %s", o.path) // reviewers still see that each changed
		}
	}
	for _, p := range []string{"web/vendor/pdfjs/pdf.js", "web/app.min.js", "go.sum", "gen/api.go", "web/worker.mjs", "logo.png"} {
		if !got[p] {
			t.Errorf("%s was not omitted", p)
		}
	}
}

func TestChunksFitTheBudgetAndKeepEveryHunk(t *testing.T) {
	var b strings.Builder
	for i := 0; i < 12; i++ {
		b.WriteString(fileDiffText(fmt.Sprintf("pkg/f%d.go", i), 4, 40, "x = 1"))
	}
	text := b.String()
	parts := chunkDiff(splitReviewable(text), 2000)
	if len(parts) < 2 {
		t.Fatalf("parts = %d", len(parts))
	}
	var joined strings.Builder
	for _, p := range parts {
		if estimateTokens(p.text) > 2000 {
			t.Errorf("%s is %d tokens", p.label(), estimateTokens(p.text))
		}
		if p.total != len(parts) || p.label() != fmt.Sprintf("part %d of %d", p.index, len(parts)) {
			t.Errorf("label %q", p.label())
		}
		joined.WriteString(p.text)
	}
	for _, line := range strings.Split(text, "\n") {
		if (strings.HasPrefix(line, "+x") || strings.HasPrefix(line, "@@")) && !strings.Contains(joined.String(), line) {
			t.Errorf("lost %q", line)
		}
	}
}

